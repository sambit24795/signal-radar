function ContactLine() {
  if (!CONTACT_EMAIL) return <p>Reply to any email from {LEGAL_NAME} and we will help.</p>;
  if (CONTACT_EMAIL.toUpperCase() === 'TODO') {
    return (
      <p>
        Email <span className="warn">TODO</span>.
      </p>
    );
  }
  return (
    <p>
      Email{' '}
      <a className="link" href={`mailto:${CONTACT_EMAIL}`}>
        {CONTACT_EMAIL}
      </a>
      .
    </p>
  );
}

